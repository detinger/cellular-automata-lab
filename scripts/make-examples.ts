// Example files for docs and tests, built from presets. Bundled and run by scripts/make-examples.mjs.
import { presetById } from '../src/data/presets';
import { exportModelJson } from '../src/interchange/modelJson';
import { draftExperiment } from '../src/features/experiments/drafts';
import { planRuns } from '../src/domain/experiments/experiment';
import { executeRun } from '../src/domain/experiments/execute';
import { experimentJson } from '../src/interchange/experimentExport';

export function examples(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [file, id] of [
    ['glider-torus.ca.json', 'glider'],
    ['sir-outbreak.ca.json', 'sir-outbreak'],
    ['majority-vote.ca.json', 'majority-vote'],
  ] as const)
    out[file] = exportModelJson(presetById(id)!.build(), `example-${id}`, `example-${id}-r1`);
  const m = presetById('sir-outbreak')!.build();
  const def = {
    ...draftExperiment(m, 'example-sir-outbreak', 'example-sir-outbreak-r1', 'see-model-file'),
    id: 'exp-example-sir-beta',
    name: 'SIR: final recovered share vs β',
    createdAt: '2026-11-10T00:00:00.000Z',
    masterSeed: '2026',
    question: 'How does β change the final recovered share?',
    hypothesis: 'Higher β gives a larger outbreak.',
    replicates: 3,
    horizon: 100,
  };
  const runs = planRuns(def)
    .map((s) => executeRun(def, s))
    .map((r) => ({ ...r, startedAt: '2026-11-10T00:00:00.000Z', endedAt: '2026-11-10T00:00:00.000Z', wallMs: 0 }));
  out['sir-beta-sweep.ca-experiment.json'] = experimentJson(def, runs, {
    includeSamples: false,
    conclusion: '',
    runtime: 'generated by scripts/make-examples.mjs',
    status: 'completed',
  }).replace(/"exportedAt": "[^"]+"/, '"exportedAt": "2026-11-10T00:00:00.000Z"');
  return out;
}
