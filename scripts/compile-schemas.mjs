// Compiles owned JSON Schemas to standalone validators at build time, so the
// browser never needs runtime code generation (keeps the CSP free of 'unsafe-eval').
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const schema = JSON.parse(await readFile(new URL('../src/schemas/model.v1.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv({ code: { source: true, esm: true }, allErrors: true, strict: true });
const validate = ajv.compile(schema);
const out = new URL('../src/schemas/generated/', import.meta.url);
await mkdir(out, { recursive: true });

// Ajv's ESM output still require()s its runtime helpers; swap them for ESM imports.
let code = standaloneCode(ajv, validate);
const imports = new Set();
code = code.replace(/require\("(ajv\/dist\/runtime\/[a-z0-9]+)"\)\.default/g, (_, mod) => {
  const name = '__' + mod.split('/').pop();
  imports.add(`import ${name}_m from "${mod}.js";\nconst ${name} = typeof ${name}_m === "function" ? ${name}_m : ${name}_m.default;`);
  return name;
});
if (/require\(/.test(code)) throw new Error('Unhandled require() in generated validator');

const header = '// @ts-nocheck\n// Generated by scripts/compile-schemas.mjs from model.v1.schema.json. Do not edit.\n';
await writeFile(new URL('modelV1.validate.js', out), header + [...imports].join('\n') + '\n' + code.replace('"use strict";', ''));
console.log('Compiled model.v1.schema.json');
